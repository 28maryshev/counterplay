namespace Counterplay;

/// <summary>
/// Подмена базы под работающим движком: закрыть движок, подменить файл,
/// собрать движок заново.
///
/// Главное правило: **движок собирается заново в любом случае**. Если подмена
/// не вышла (файл держит кто-то ещё), движок встаёт на прежнюю базу, а
/// скачанное ждёт следующей попытки. Раньше при неудаче программа оставалась
/// без движка до перезапуска: рекомендации не считались, центр окна драфта
/// висел на заглушке (журнал 2026-11-08).
///
/// Повтор после неудачи — не раньше <see cref="RetryPause"/>. Подмену пробуют
/// на каждом событии фазы вне драфта (в лобби их десяток в минуту), а сборка
/// движка — полный проход по таблице связок. Без паузы программа, у которой
/// файл держит соседний экземпляр, пересобирала бы движок без конца.
///
/// Тип движка — параметр: проверке не нужна настоящая база с таблицами, ей
/// хватает соединения, которое держит файл так же, как держит движок.
/// </summary>
public sealed class EngineSwap
{
    /// Пауза после неудачной подмены.
    public static readonly TimeSpan RetryPause = TimeSpan.FromMinutes(10);

    private readonly Func<DateTime> _now;
    private DateTime _retryAfter = DateTime.MinValue;

    /// <param name="now">Часы. Проверке — свои, чтобы не ждать паузу на деле.</param>
    public EngineSwap(Func<DateTime>? now = null) => _now = now ?? (() => DateTime.UtcNow);

    /// Пора ли пробовать: скачанное ждёт, и пауза после неудачи вышла.
    public bool Due => DataDb.SwapReady && _now() >= _retryAfter;

    /// <summary>
    /// Применить скачанную базу, если пора, и вернуть движок, на котором
    /// работать дальше.
    ///
    /// Не пора — вернёт <paramref name="current"/> нетронутым. Пора — закроет
    /// его (иначе файл не отпустить), подменит базу и вернёт то, что соберёт
    /// <paramref name="rebuild"/>: на свежей базе, если подмена вышла, на
    /// прежней — если нет. Исключение из <paramref name="rebuild"/> уходит
    /// наружу; прежний движок к этому моменту уже закрыт, отдавать его нельзя.
    /// </summary>
    public T? Apply<T>(T? current, Func<T?> rebuild, out bool swapped) where T : class, IDisposable
    {
        swapped = false;
        if (!Due) return current;

        current?.Dispose();                 // отпускаем файл базы
        swapped = DataDb.ApplySwap();
        if (!swapped) _retryAfter = _now() + RetryPause;
        return rebuild();
    }

    /// <summary>
    /// Закрыть движок при любом выходе из сессии клиента.
    ///
    /// Обрыв связи с клиентом выходит из сессии исключением, и закрытие в
    /// конце метода не выполнялось. Брошенный движок держал файл базы до
    /// перезапуска программы, а следующая сессия собирала второй рядом. Из-за
    /// него скачанная фоном база не подменялась никогда.
    ///
    /// <paramref name="current"/> читается в момент выхода: движок за сессию
    /// пересобирается (смена ранга, подмена базы), закрыть надо последний.
    /// </summary>
    public static IDisposable CloseOnExit(Func<IDisposable?> current) => new Closer(current);

    private sealed class Closer(Func<IDisposable?> current) : IDisposable
    {
        public void Dispose() => current()?.Dispose();
    }
}
