namespace Counterplay;

/// <summary>
/// Песочница не пишет в данные игрока.
///
/// Она работает рядом с боевой программой на тех же файлах в %APPDATA%:
/// журнале игр, настройках, пулах, пароле синхронизации. Каждая её запись —
/// запись поверх живой программы. Та держит те же данные в памяти и своей
/// записью затрёт песочницу, а песочница — её. Журнал игр так терял бы игры,
/// настройки откатывались бы к виду на момент запуска песочницы, очередь
/// графика в сайдбаре переключалась бы сама, а синхронизация увозила бы всё
/// это на сервер.
///
/// Поэтому в песочнице данные игрока только читаются. Что в ней поменяли,
/// живёт в памяти до закрытия. Своё — пулы, журнал, выбор профиля — песочница
/// держит в <see cref="Dir"/>.
/// </summary>
public static class Sandbox
{
    /// Включается при запуске песочницы, выключается при переходе в боевой режим.
    public static bool Active { get; set; }

    /// Папка песочницы: %APPDATA%\Counterplay\sandbox.
    public static string Dir => Path.Combine(
        AppPaths.Root, "sandbox");
}
