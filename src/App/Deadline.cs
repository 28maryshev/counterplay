namespace Counterplay;

/// <summary>
/// Подождать задачу, но не дольше отведённого срока.
///
/// Нужно там, где чужая медлительность не должна задерживать своё дело:
/// проверка обновлений на запуске ходит на GitHub, а тот иногда отвечает
/// минутами. Программа из-за этого не открывалась — при том, что работать ей
/// ничто не мешало.
///
/// Не уложилось — возвращаем null и идём дальше. Задача при этом никуда не
/// девается: она доживёт своё в фоне, просто её результат больше никому не
/// нужен. Отменить её мы не можем — Velopack не принимает признак отмены.
/// </summary>
public static class Deadline
{
    /// <summary>
    /// Результат задачи или null, если она не уложилась в <paramref name="limit"/>.
    ///
    /// Отмена (<paramref name="ct"/>) и ошибка самой задачи проходят наружу:
    /// первое означает «программа закрывается», второе зовущий пишет в журнал.
    /// Молчать о них нельзя — «не обновляется» и так самая частая жалоба.
    /// </summary>
    public static async Task<T?> OrNull<T>(Task<T?> work, TimeSpan limit, CancellationToken ct = default)
        where T : class
    {
        try
        {
            return await work.WaitAsync(limit, ct);
        }
        catch (TimeoutException)
        {
            // Брошенную задачу «досматриваем»: упадёт она позже — и ошибка
            // всплывёт ничьей, без связи с местом, где возникла. Проверкой это
            // не подтвердить (WaitAsync, похоже, и сам её видит), но строка
            // дешёвая, а разбирать потом ничью ошибку в журнале — дорого.
            _ = work.ContinueWith(t => _ = t.Exception,
                                  TaskContinuationOptions.OnlyOnFaulted);
            return null;
        }
    }
}
