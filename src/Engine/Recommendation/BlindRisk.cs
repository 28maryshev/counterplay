namespace Counterplay;

/// <summary>
/// Чем грозит взять чемпиона, пока соперник одной роли ещё не выбран.
/// Value — ожидаемый матчап против того, кого возьмут в ответ, пп, относительно
/// типичного чемпиона моей роли (0 — как у всех, плюс — надёжнее, минус —
/// легче законтрить). Chance — шанс, что в пуле соперника найдётся контра
/// (0…1); Typical — тот же шанс у типичного чемпиона роли в этом драфте (на
/// топе контры есть почти у всех, в лесу — почти ни у кого). Spread — истинный
/// разброс матчапов, пп. Counters — самые частые из доступных контр, по пикрейту.
/// Verdict — вывод для игрока: +1 надёжен вслепую, −1 рискован, 0 — как все
/// (пороги — в движке, один раз на карточку подбора и на строку пула).
/// </summary>
public sealed record BlindRisk(double Value, double Chance, double Typical, double Spread,
                               IReadOnlyList<int> Counters, int Verdict)
{
    public static readonly BlindRisk None = new(0, 0, 0, 0, [], 0);
}
