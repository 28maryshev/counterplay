    // сигнатуры. Оверлей по нему красит маркер строки: зелёный — довод «за»,
    // красный — «против», серый — нейтральный факт.
    public const char SIGN_GOOD = '';

    public const char SIGN_BAD  = '';

    /// <summary>
    /// Довод, который нельзя выбрасывать как «общий». Такова связка с конкретным
    /// союзником: «Ясуо ультует в твой подброс» одинакова у всех подкидывающих
    /// кандидатов — и отсев общих строк убирал её у ВСЕХ разом, хотя ради неё
    /// пик и берут. Знак читается как «за», но помечен отдельно.
    /// </summary>
    public const char SIGN_KEY  = '';

    private static string Good(string s) => SIGN_GOOD + s;

    private static string Bad(string s)  => SIGN_BAD + s;

    private static string Key(string s)  => SIGN_KEY + s;

    // Лаплас-сглаживание: при малом числе игр тянем к 50%.
    private const double K      = 50.0; // для базового WR (данных много)

    private const double K_PAIR = 20.0; // для парных таблиц (синергия/матчап) — данных мало

    private const double PRIOR  = 0.5;

    private const double CONF_GAMES = 60.0;  // темпер синергии по объёму выборки

    private const double BASE_CONF  = 250.0; // темпер базового WR по объёму выборки

    // Доверие к парному матчапу в подборе: g / (g + PAIR_CONF). Было 50 (общее с
    // MATCHUP_CONF) — пара на 500 играх весила 0,91 от пары на десяти тысячах,
    // хотя на 500 играх шум пары (±2,2 пп) больше всей разницы между
    // матчапами. Подобрано по исходам 05.11.2026 (calibrate.py, перебор 50 …
    // 8000 отдельно для своей линии и для пар разных ролей): у 1000 правдоподобие
    // исходов выше на 377 единиц логарифма, оптимум пологий (300–1000 для линии,
    // 1000 для чужих). Доли правды ниже (LaneTrust, CrossTrust) намеряны при
    // нём — меняешь его, перемеряй их. Им же считается подсветка врагов при
    // наведении (VersusDelta): цифра одна.
    private const double PAIR_CONF = 1000.0;

    // Доверие пары в синергии по союзникам и в советах банов — не мерено, 50.
    private const double MATCHUP_CONF = 50.0;

    // Приор по всем дивизионам для разреженных пар. В своём бакете у половины пар
    // меньше 15 взвешенных игр, и темпер выше режет их дельту до ~22%. База везёт
    // сводку той же пары по всем дивизионам (tier_bucket='all', patch='all') —
    // подмешиваем её как POOL_PRIOR «псевдо-игр» с винрейтом сводки.
    //
    // Почему приором, а не сложением игр: у соседних эло та же пара играется иначе,
    // и их объём не должен спорить со своим бакетом. Пара с 500 своими играми
    // сдвинется на сотые доли процента, пара с нулём получит осмысленную оценку
    // вместо молчания.
    private const double POOL_PRIOR = 25.0;  // сколько «псевдо-игр» даёт сводка

    private const double POOL_MIN   = 30.0;  // ниже этого сводка шумит сама

    // Взвешивание патчей по свежести: текущий патч — полный вес, предыдущие затухают.
    // Все агрегаты считают SUM(games*вес): мета следует за актуальным патчем, не
    // теряя объёма старых данных (эффективная выборка ≈76% от плоской суммы).
    // Вес патча по свежести. Третий слот остаётся на случай, если патчей в базе
    // меньше и @p3 совпадает с @p2 (см. Create) — тогда вес просто не сработает.
    private const string PW = "CASE patch WHEN @p1 THEN 1.0 WHEN @p2 THEN 0.6 ELSE 0.3 END";

    // ── Вес контры на линии: по исходам матчей ──────────────────────────────
    // Цифра контры (матчап минус своя база, с доверием по объёму PAIR_CONF) —
    // это правда пополам с шумом малых выборок, и доля правды у ролей разная.
    // Замер pipeline/calibrate.py: 636 тыс. драфтов изумруда 16.21,
    // логистическая регрессия «разность факторов команд → победа», из
    // агрегатов вычтен сам матч. Сколько настоящих пунктов победы несёт один
    // показанный пункт контры (05.11.2026, при PAIR_CONF = 1000):
    //
    //   топ 1,39 · мид 1,24 · саппорт 1,00 · лес 0,91 · АДК 0,81 (±0,05–0,07)
    //   бот 2 на 2 (АДК против их саппорта и наоборот) 0,88
    //
    // Больше единицы у топа и мида — показанная цифра там занижает правду:
    // при доверии 1000 пара усаживается к нулю сильнее, чем нужно этим линиям.
    // Первый замер (04.11, при доверии 50) давал 0,71 / 0,70 / 0,49 / 0,40 /
    // 0,53 — там в цифре было много шума малых пар, а лес выходил меньше всех.
    // До замеров веса были на глаз (топ 2,5, лес 2,2, мид 2,0, саппорт 2,0, АДК
    // 1,8).
    //
    // Вес = W_COUNTER_PP × доля правды: пункт настоящей контры стоит одинаково
    // на всех ролях — 3,7 очка оценки. Это число и сохраняется при перемерах,
    // а не средний вес: вес — на показанный пункт, и при другом доверии пары
    // показанный пункт другой. 3,7 выбрано 04.11 так, чтобы средний вес тогда
    // остался прежним (2,1). Перемерять — тем же calibrate.py раз в несколько
    // патчей.
    //
    // Пункт контры при этом весит в 4,3 раза больше пункта силы (сила — 0,86
    // очка за настоящий пункт): сильная известная контра даёт до ~10 очков и
    // перебивает наигранность. Это оставлено нарочно — решение владельца
    // 06.11.2026: без пула контра и должна решать, а у кого пул, мейны и так
    // стоят отдельными карточками пула (TopFromPool) с прибавкой комфорта.
    // Снижать — только по его слову.
    private const double W_COUNTER_PP = 3.7;

    private static double LaneTrust(string role) => role switch
    {
        "top"     => 1.39,
        "jungle"  => 0.91,
        "mid"     => 1.24,
        "adc"     => 0.81,
        "support" => 1.00,
        _         => 1.07,
    };

    private static double DirectWeight(string role) => W_COUNTER_PP * LaneTrust(role);

    // Бот 2 на 2: АДК против их саппорта и саппорт против их АДК — одни и те
    // же игры с двух сторон, доля правды одна. Раньше вес рос, когда виден
    // весь их бот (1,5 → 1,8); замер этого не подтверждает — пункт контры
    // стоит столько же, известен второй враг или нет.
    private const double BOT_DUO_TRUST = 0.88;

    private const double W_BOTLANE = W_COUNTER_PP * BOT_DUO_TRUST;

    // Прочие враги (не соперник по линии и не дуо врага): у каждой пары ролей
    // своя доля правды, тот же замер. Каждый враг — своим слагаемым
    // W_COUNTER_PP × доля × его пара, и они СКЛАДЫВАЮТСЯ: исход зависит от всех
    // матчапов сразу. До 05.11.2026 все прочие сливались в одну пару (средняя
    // по играм) с весом 1.2 на всех, и вес на каждого врага выходил 1.2 / их
    // число — от числа видимых врагов, а не от того, кто против кого. Саппорт
    // против их топа — 0,35, лес против их мида — 0,88: лесу важны все линии.
    // Пара АДК и саппорта — та же, что у бота 2 на 2 (враг-дуо, чья роль
    // угадана, а не открыта клиентом).
    private static double CrossTrust(string a, string b) =>
        (string.CompareOrdinal(a, b) < 0 ? (a, b) : (b, a)) switch
        {
            ("adc", "jungle")     => 0.62,
            ("adc", "mid")        => 0.61,
            ("adc", "support")    => BOT_DUO_TRUST,
            ("adc", "top")        => 0.61,
            ("jungle", "mid")     => 0.88,
            ("jungle", "support") => 0.80,
            ("jungle", "top")     => 0.59,
            ("mid", "support")    => 0.54,
            ("mid", "top")        => 0.43,
            ("support", "top")    => 0.35,
            _                     => 0.0,
        };

    private static double CrossWeight(string myRole, string vsRole) => W_COUNTER_PP * CrossTrust(myRole, vsRole);

    // Вслепую в «против оппонента» и «против их дуо» идёт ожидаемое по
    // усаженным парам (BlindMath) — оно уже очищено от шума, то есть уже в
    // настоящих пунктах. Поэтому вес без доли правды: столько же, сколько
    // пункт настоящей контры.
    private const double W_BLIND = W_COUNTER_PP;

    private const double W_BASE    = 1.0;

    // «Прочие враги» через same-role таблицу: контекст кривой (матчап «как если
    // бы он был моим лейн-оппонентом»), покрытие ~22% — держим вес низким.
    // Основной канал для прочих врагов — кросс-ролевые матчапы (CrossWeight);
    // этот — запасной, когда пары разных ролей в базе нет.
    private const double W_OTHER   = 0.6;

    private const double W_SYNERGY = 1.2;

    // Напарник по дуо-пулу — не случайный союзник. Таблицы синергии собраны по
    // НЕсогласованному соло-кью и занижают связку, которую играют осознанно: пара
    // созванивается, размены и заходы у неё получаются чаще. Поэтому вклад
    // напарника в синергию считаем с множителем.
    //
    // 1.5 — величина выбранная, а не измеренная: проверить её по данным нельзя,
    // в матчах Riot нет отметки, кто был в пати. Выбрана по замеру (tests/PoolBias):
    // на наигранной связке хвосты прибавки ±2.6 очка — около четырёх шагов между
    // соседями в топ-10, и общий лидер меняется в 18% драфтов. На 2.0 и выше —
    // 39–56%: синергия начинает перебивать контрпик, а этого мы избегаем и в
    // W_SYN_MAX. Выше 1.5 не поднимать — решение владельца, и его держит сторож
    // в PoolBias, читающий эту строку. Надбавка ДВУСТОРОННЯЯ: плохую связку она
    // так же уводит вниз, и это половина её пользы.
    private const double DUO_MATE_MULT = 1.5;

    // Насколько громко эта надбавка звучит — по тому, сколько вы РЕАЛЬНО играете
    // вдвоём за окно свежести. Случайный сопартиец из нормала не должен гнуть
    // совет так же, как напарник, с которым за месяц сыграно двадцать игр.
    //
    // Считаем по играм с ЧЕЛОВЕКОМ, а не по паре чемпионов. Замер на живой
    // истории: из 251 записи связок у 250 ровно ОДНА игра, с тремя играми нет ни
    // одной записи. Порог на паре чемпионов не сработал бы никогда, а винрейт
    // такой пары — это 0% или 100%, то есть шум.
    //
    // Половина веса набирается к шести играм: 1 → 0.14, 3 → 0.33, 6 → 0.50,
    // 20 → 0.77. Сглаживание, а не обрыв, — как у наигранности (RECENT_K).
    private const double MATE_CONF = 6.0;

    private const double W_POOL     = 1.0; // вес «комфорта» (наигранность чемпиона)

    // Личный винрейт игрока на чемпионе за последний месяц (соло+флекс+нормалы,
    // ARAM не в счёт). Был 0.5 — намеренно ниже мета-факторов. Поднят до 1.0
    // вместе с урезанием пожизненного мастерства: «на нём у меня СЕЙЧАС идёт» —
    // сигнал более свежий и более честный, чем «я когда-то его много играл».
    private const double W_PERSONAL = 1.0;

    // С какого числа игр проценту на чемпионе верим полностью. Окно — месяц, и
    // за месяц на одном чемпионе набирается около тридцати игр: это и есть
    // «доказанный» результат. До тридцати доверие растёт как КВАДРАТ доли:
    // 10 игр — 1/9 веса, 15 — четверть, 20 — 0.44, 30 и дальше — целиком.
    //
    // Квадрат, а не прямая, нарочно. На прямой серия 6–0 (+50 пп при пятой
    // части доверия) весила бы столько же, сколько 60% на тридцати играх. Владелец
    // хочет, чтобы объём решал: 56% на сотне лучше, чем 66% на девяти, и то же в
    // масштабе месяца — 57% на 30 играх (+2.33) против 66% на 9 (+0.52), серии
    // 6–0 / 8–2 / 9–1 (+0.70 / +1.17 / +1.56) против 60% на 30 (+3.50).
    //
    // История формулы. Сглаживание на 12 игр × g/(g+15) упиралось в потолок уже
    // на сериях: 6–0, 8–2 и 56% на сотне получали одинаковые +4. Сглаживание на
    // 100 игр развело их, но было рассчитано на сотню игр, которой за месяц не
    // бывает: на тридцати играх 60% давали всего +2.3, а 9–1 — больше (+3.6).
    private const double PERSONAL_FULL_GAMES = 30.0;

    // Сколько очков даёт один пункт процента при полном доверии: 60% на 30
    // играх — +3.5, 57% — +2.3, 53% — +1.2.
    private const double PERSONAL_SCALE = 0.35;

    // Потолок личной дельты. Без него 70% на 30 играх давали бы +7 — больше, чем
    // прямой контрпик, и подбор превращался бы в «играй что привык». При весе 1.0
    // потолок 4.0 даёт максимум +4 очка — вровень с сильным контрпиком, но не
    // выше: личный винрейт подсказывает выбор, а не отменяет матчап. Достаётся
    // он только доказанному: от ~61.5% на тридцати играх.
    private const double PERSONAL_CAP = 4.0;

    // ── Пик вслепую (BlindMath, часть Blind) ────────────────────────────────
    // Пока соперник на линии не выбран, вместо нуля в «против оппонента» идёт
    // ожидаемый матчап против того, кого возьмут в ответ, — с весом W_BLIND
    // (пункт настоящей контры, см. выше). Так при первом пике чемпион,
    // которого легко законтрить, уступает надёжному.
    //
    // Пул соперника: 80% мастерства мидера в среднем покрывают 7 чемпионов.
    // Своих данных о пулах у нас нет (мастерство чужих игроков не собираем).
    private const int BLIND_POOL = 7;

    // Какая доля соперников берёт контру, а не своё. Выбрано, а не измерено:
    // Riot не отдаёт порядок пиков, и по матчам не отличить «контрил» от
    // «взял своё и попал». Половина — середина между «никто не смотрит» и
    // «все смотрят». При 0,5 разрыв между Ари (+0,36) и Талией (−0,60) на
    // миде — около 3,6 очка оценки (до калибровки весов, 04.11, — около двух):
    // заметно, но мейн (наигранность до +6, личный винрейт до +4) это перебивает.
    private const double BLIND_COUNTER_RATE = 0.5;

    // Строка «вслепую» в карточке: шанс нарваться на контру на столько ниже
    // или выше типичного для роли, а «надёжен» — ещё и с плюсом в ожидаемом,
    // пп. Типичный шанс по ролям (замер 04.11, изумруд): топ 59%, мид 53%,
    // саппорт 30%, АДК 18%, лес 14% — поэтому порог относительный: на топе
    // контры есть почти у всех, в лесу почти ни у кого. При 10 пунктах на
    // миде Ари (34%) — «надёжна», Ясуо (65%) — «рискован».
    private const double BLIND_CHANCE_GAP = 0.10;

    private const double BLIND_REASON_PP  = 0.15;

    // Поле соперника вслепую по уже взятым врагам (FieldWeights): сколько
    // «псевдо-игр» тянут долю пары к безусловной. Замер 05.11.2026 — угадывание
    // их саппорта по их АДК: m = 50 → +14,6%, 200 → +14,6%, 1000 → +14,4%,
    // 5000 → +13,9% (на драфт, по логарифму правдоподобия); середина пологого
    // оптимума.
    private const double FIELD_PRIOR = 500;

    // Против стиля врага (DraftFit, части — StyleParts). Были на глаз 0.8 и 0.6;
    // замер по исходам (05.11.2026, тот же calibrate.py при PAIR_CONF = 1000,
    // признаки по драфтам — Counterplay.exe --style-features): трифекта
    // архетипов — 0,099 ± 0,064 настоящего пункта на единицу, инструменты против
    // стиля («прикрывает от дайва») — 0,022 ± 0,017, почти ноль. Вес =
    // W_COUNTER_PP × замер, как у контры. До замера «прикрывает от дайва» давало
    // саппорту до +3 очков — больше любой измеренной контры в драфте.
    private const double W_TRIFECTA = 0.37; // архетип-контра (камень-ножницы-бумага)

    private const double W_STYLE    = 0.08; // анти-стиль: инструменты против компы врага

    private const double W_VULN     = 2.0; // штраф за стак одной уязвимости в команде

    private const double W_EXPLOIT  = 1.0; // бонус за наказание вынужденного предмета врага

    private const double W_STRUCT   = 1.6; // структурная синергия с ключевым тиммейтом (jg↔линия, адк↔сапп)

    private const double W_DMGBAL   = 1.2; // баланс типа урона (AD/AP): не стакать один тип

    // Закрывает дыру состава (Needs.cs). Цены дыр (GapWeight) — в настоящих
    // пунктах победы по замеру 09.11.2026, поэтому вес — цена пункта, как у
    // контры. Потолок — NEED_BONUS_MAX 1,5 пп × W_NEED ≈ 5,6 очка у последнего
    // пика (волны + пил + танки). Решение владельца 09.11 («делай» — вес в счёте).
    private const double W_NEED     = W_COUNTER_PP;

    // ARAM (врагов нет; максимизируем сочетание команды).
    private const double W_ARAM_SYN  = 1.8; // синергия с союзниками — главное

    private const double W_ARAM_DMG  = 2.0; // смешанный урон крайне важен

    private const double W_ARAM_GAP  = 1.0; // закрытие «дыр» композиции (фронт/саст/поук)

    private const double W_ARAM_BASE = 1.0; // сила чемпиона (WR без роли)

    /// За сколько дней считаем «чем игрок играет сейчас» для защитных банов —
    /// то же окно, что у наигранности и личного винрейта (см. FreshDays), и
    /// по той же причине: короче — и после недельного перерыва список опустеет,
    /// длиннее — и туда снова полезут давно брошенные чемпионы. Окно одно на
    /// всех, поэтому отдельной константы у банов больше нет.
    /// Сколько мейнов защищаем. Больше пяти — и бан начинает защищать случайное.
    private const int MainsTake = 5;

    // Порог включения бот-матчапов: сумма игр в botlane_matchup. ~20k записей —
    // это примерно столько же матчей с собранной бот-статистикой (по ~1 на пару).
    private const double BOTLANE_MIN_GAMES = 20000;

    // Веса рейтинга банов (RecommendBans). Очки кандидата — сумма по нашим
    // чемпионам: сила контры (очки винрейта) × вес нашего × встречаемость ×
    // место в тир-листе (сила в патче — только здесь, один раз на все линии).
    // Веса ниже — веса НАШИХ чемпионов.
    private const double W_BAN_META    = 1.0; // защищать некого: очки = множитель моей линии × это

    private const double W_BAN_POOL    = 4.5; // весь мой пул вместе (делится по корню из игр)

    private const double W_BAN_MYPICK  = 3.2; // мой наведённый/взятый пик

    private const double W_BAN_ALLY    = 2.6; // наведённый/взятый пик союзника

    private const double W_BAN_HOVER   = 1.8; // то, что союзник наводил раньше

    // Жёсткая контра моему чемпиону (пик или пул): бьёт его на BAN_HARD очков
    // винрейта и больше — её очки × W_BAN_HARD, и одна такая всегда в пятёрке.
    private const double BAN_HARD   = 3.0;

    private const double W_BAN_HARD = 1.6;

    // С какой силы контра «заметная»: называется в подписи, засчитывает линию
    // для BAN_FLEX и прикрывает наш пик — следующий бан против него × BAN_REPEAT
    // (прикрытие — доля силы до BAN_HARD: слабое попадание прикрывает частично).
    private const double BAN_HIT = 1.0;

    private const double BAN_REPEAT = 0.7;

    // Бьёт наших на нескольких линиях — очки × (1 + BAN_FLEX за каждую сверх первой).
    private const double BAN_FLEX = 0.3;

    // Место в тир-листе роли: первый × BAN_TIER_HIGH, последний и вне тир-листа × BAN_TIER_LOW.
    private const double BAN_TIER_LOW  = 0.8;

    private const double BAN_TIER_HIGH = 1.4;

    // Мой пул против кандидата на ДРУГОЙ линии в той же игре (CrossOf): очки
    // × W_BAN_CROSS, доверие к паре — g / (g + CROSS_CONF). Пары игр, а не линии:
    // связь слабее и шумнее, поэтому доверие набирается в десять раз медленнее,
    // чем у матчапа на линии (MATCHUP_CONF), и весит она вдвое меньше: с весом 1
    // Джинкс набирал за «мешает пулу саппорта» больше, чем Наутилус за жёсткую
    // контру Зерату, и прямых контр пулу в пятёрке оставалась одна.
    private const double W_BAN_CROSS = 0.5;

    // Сколько банов из пяти — прямые контры моему пулу или пику на линии.
    private const int BAN_POOL_MIN = 2;

    private const double CROSS_CONF = 500.0;

    // Союзников больше стольких — вес каждого × √(BAN_ALLY_SHARE / n): трое —
    // по 0,82, четверо — по 0,71 от W_BAN_ALLY (вместе 2,4 и 2,8 пика).
    private const double BAN_ALLY_SHARE = 2.0;

    // Доля мейна в весе пула — exp(очки подбора пика / BAN_PICK_TEMP): три очка
    // разницы — в e раз. У владельца на драфте с Мундо, Каином, Мальзахаром и
    // Джинкс: Сона 27%, Браум 23%, Поппи 16% … Эш 0,6%.
    private const double BAN_PICK_TEMP = 3.0;

    // Строка карточки про мой пул или пик встаёт второй (после самой весомой),
    // если за неё набрано хотя бы столько очков.
    private const double BAN_REASON_MINE = 1.0;

    // Жёсткая контра засчитывается против чемпиона пула с долей не меньше этой.
    private const double BAN_HARD_SHARE = 0.05;

    // На ком у меня столько игр за месяц на этой роли — того не баню (мой).
    private const int BAN_OWN_GAMES = 3;

    // Мейны для банов: журнал за месяц (вес — игры) и активный пул на роль из
    // профиля. Чемпион пула без игр весит как три игры; берём восемь самых весомых.
    private const double POOL_MAIN_GAMES = 3;

    private const int MAINS_FOR_BANS = 8;

    // Минимум игр на роли суммарно по всем агрегируемым патчам. 150 отсекает
    // «мем-роли» (Нидали-саппорт с 139 играми = ~0.1% пикрейта) из кандидатов.
    private const int MIN_GAMES = 150;

    // Плюс минимальная ДОЛЯ игр роли: 0.5% отсекает редкие офф-мета пики
    // (Амуму/Фиддл-саппорт с 0.3%), даже когда абсолютных игр набралось; порог
    // сам масштабируется с размером базы.
    private const double MIN_ROLE_SHARE = 0.005;

    // Боковые подсказки (контры у врагов / синергия у союзников) ранжируем по
    // нижней границе Уилсона и показываем только при достаточной выборке. Иначе
    // всплывал шум: пара на 10–15 играх со случайным перевесом выдавалась за
    // «контру» (напр. Сион «контрил» Кейл на 16 играх, хотя реально проигрывает).
    private const int    HINT_MIN_GAMES = 30;   // минимум совместных игр на пару (контры)

    private const int    HINT_FILL_GAMES = 10;  // при доборе до трёх порог ниже

    private const double HINT_EVEN_WR   = 0.49; // ровная пара: годится третьей, проигрышная — нет

    private const int    HINT_MIN_SYN   = 12;   // ниже порог для синергии — чтобы заполнять 3

    private const double HINT_MIN_EDGE  = 0.50; // контру показываем, только если LB Уилсона > 50%

    private const double WILSON_Z       = 1.28; // ~80% односторонняя уверенность

    // Количество патчей для агрегации (берём последние N).
    // Два патча, а не три. Патчи выходят раз в ~2 недели, и третий по счёту —
    // это данные полуторамесячной давности: мета за это время успевает смениться,
    // а объёмом (миллионы игр) они перевешивали свежие. Замер по базе: отказ от
    // третьего патча срезает покрытие матчапов лишь на ~16 %, зато решение
    // перестаёт опираться на позапрошлую мету.
    private const int PATCH_WINDOW = 2;
