// Движок подбора — веса скоринга, сглаживание и пороги выборок. Все настраиваемые числа
// подбора — здесь (tests/PoolBias читает DUO_MATE_MULT и W_SYNERGY отсюда).
public sealed partial class RecommendationEngine
{
    // Знак причины — невидимым префиксом в самой строке: так он доезжает до
