// Номер патча для показа игрокам.
//
// В данных патч хранится так, как его отдаёт Riot API / Data Dragon (16.16), а в
// самой игре и в патчноутах этот же патч называется 26.16: Riot ведёт две линейки
// со сдвигом ровно в 10 мажорных версий. Наружу показываем игровой номер — его
// игроки видят в клиенте и ищут в поиске.
function displayPatch(patch) {
  const m = /^(\d+)\.(\d+)/.exec(String(patch ?? ''));
  return m ? `${Number(m[1]) + 10}.${m[2]}` : String(patch ?? '');
}

module.exports = {displayPatch};
